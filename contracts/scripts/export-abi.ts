// Task A4: write lib/chain/abi.ts from the compiled SurveyEscrow artifact.
//
//   npx hardhat build && npx hardhat run scripts/export-abi.ts
//
// The ABI is frozen after deployment (AGENTS.md rule 10).
import { writeFile } from 'node:fs/promises';
import hre from 'hardhat';

const artifact = await hre.artifacts.readArtifact('SurveyEscrow');

const body = `// Generated by contracts/scripts/export-abi.ts from SurveyEscrow. Do not edit by hand.
// FROZEN after deployment: changes need all three devs to agree. Browser and server safe.
import type { Address } from 'viem';

export const ESCROW_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** From NEXT_PUBLIC_CONTRACT_ADDRESS. Empty until the contract is deployed (task A4). */
export const ESCROW_ADDRESS = (process.env.NEXT_PUBLIC_CONTRACT_ADDRESS ?? '') as Address;
`;

const out = new URL('../../lib/chain/abi.ts', import.meta.url);
await writeFile(out, body);
console.log(`Wrote lib/chain/abi.ts (${artifact.abi.length} ABI entries)`);
